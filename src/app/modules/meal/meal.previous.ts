const getMeals = async (req: Request) => {
  const { skip, take, limit, page, search } = paginationHelper(
    req.query as any,
  );
  const meals = await prisma.meal.findMany({
    where: {
      mealName: {
        contains: search,
        mode: "insensitive",
      },
    },
    skip,
    take,
    orderBy: {
      createdAt: "desc",
    },
    include: {
      food: {
        select: {
          id: true,
          foodName: true,
          foodImage: true,
          extras: true,
        },
      },
    },
  });
  const totalMeals = await prisma.meal.count({
    where: {
      mealName: {
        contains: search,
        mode: "insensitive",
      },
    },
  });

  return {
    totalMeals,
    totalPages: Math.ceil(totalMeals / limit),
    currentPage: page,
    meals,
  };
};

