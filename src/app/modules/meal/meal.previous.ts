const myMealPlans = async (userId: string, day: string) => {
  const parsedDate = parse(day, "dd-MM-yyyy", new Date());

  if (isNaN(parsedDate.getTime())) {
    throw new Error("Invalid date format. Please use 'DD-MM-YYYY'.");
  }

  // Simulate GMT+3 by shifting the parsed date
  const gmt3Date = new Date(parsedDate.getTime() + 3 * 60 * 60 * 1000);

  // Calculate start and end of that day in GMT+3, then convert back to UTC for DB query
  const start = new Date(startOfDay(gmt3Date).getTime() - 3 * 60 * 60 * 1000);
  const end = new Date(endOfDay(gmt3Date).getTime() - 3 * 60 * 60 * 1000);

  // Fetch meal plans created within that day range
  const mealPlans = await prisma.generatedPlanWithFood.findMany({
    where: {
      userId,
      createdAt: {
        gte: start,
        lte: end,
      },
    },
    include: {
      food: {
        select: {
          id: true,
          foodName: true,
          foodImage: true,
          total: true,
          extras: true,
        },
      },
      package: {
        select: {
          packageName: true,
        },
      },
    },
  });

  if (mealPlans.length === 0) {
    return [];
  }

  if (mealPlans[0].package.packageName === "Full Package") {
    const MEAL_LIMITS: Record<string, number> = {
      breakfast: 1,
      lunch: 1,
      dinner: 1,
      snack: 2,
    };

    const reservedCountByMeal = mealPlans.reduce<Record<string, number>>(
      (acc, m) => {
        if (m.status === "Added_Cart" || m.status === "Payment_Completed") {
          acc[m.mealPlan] = (acc[m.mealPlan] || 0) + 1;
        }
        return acc;
      },
      {},
    );

    return mealPlans.map((m) => {
      const limit = MEAL_LIMITS[m.mealPlan] ?? 1;
      const reservedCount = reservedCountByMeal[m.mealPlan] || 0;

      // If limit reached, block remaining items
      if (
        reservedCount >= limit &&
        m.status !== "Added_Cart" &&
        m.status !== "Payment_Completed"
      ) {
        return { ...m, status: "Unavailable" };
      }

      return m;
    });
  }

  const slotsInCartOrPaid = new Set(
    mealPlans
      .filter(
        (m) => m.status === "Added_Cart" || m.status === "Payment_Completed",
      )
      .map((m) => m.mealPlan),
  );

  return mealPlans.map((m) =>
    slotsInCartOrPaid.has(m.mealPlan) &&
    m.status !== "Added_Cart" &&
    m.status !== "Payment_Completed"
      ? { ...m, status: "Unavailable" }
      : m,
  );
};

