const generateValidDates = (startDate: Date, totalDays: number): Date[] => {
  const dates: Date[] = [];
  let currentDate = startDate;

  while (dates.length < totalDays) {
    if (!isWeekend(currentDate)) {
      dates.push(currentDate);
    }
    currentDate = addDays(currentDate, 1);
  }

  return dates;
};

